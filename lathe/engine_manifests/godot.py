"""Godot engine manifest adapter (STAGE-10).

Emits ``<asset>.lathe_for_godot.json``. Godot's glTF importer picks up the
glb + collision meshes directly; this sidecar tells the downstream
EditorImportPlugin how to wire them into a Node3D hierarchy:

  - An outer ``Node3D`` root (tagged with ``gameplay_tags``)
  - A ``LODGroup`` (via ``visibility_range_begin/end`` metadata per LOD) wrapping
    the LOD ``MeshInstance3D`` nodes that point at ``lod_{0..3}.glb``
  - ``Marker3D``-style socket nodes (Position3D pattern) carrying ``anchor_id``
    and ``socket_type`` in the ``meta`` dict, one per declared socket
  - A ``StaticBody3D`` whose ``shape`` child references ``collision_hull.glb`` and
    a ``CollisionShape3D`` array for per-part hulls (``collision_parts.glb``)

The ``latheRuntimeSemantics`` block carries the Lathe runtime_semantics_v1
contract using Godot-style PascalCase keys (``ActiveSystems``, ``Counts``,
``Ids``) so the EditorImportPlugin can populate a generated ``Resource``
(``.tres``-equivalent) without further key translation. A parallel ``.tres``
text representation is included in ``latheRuntimeSemanticsTres`` for direct
``ResourceLoader.load()`` ingestion when the importer prefers it.
"""

from __future__ import annotations

import json
from typing import Any

from ._runtime_semantics_compact import runtime_semantics_summary


def emit_godot_manifest(context: dict[str, Any], asset_name: str) -> str:
    """Build the Godot sidecar JSON as a string (caller writes to disk)."""
    semantics = runtime_semantics_summary(context.get("runtime_semantics"))
    root: dict[str, Any] = {
        "schemaVersion": 1,
        "engine": "godot",
        "engineVersion": ">=4.2",
        "assetName": asset_name,
        "rootNode": {
            "type": "Node3D",
            "name": asset_name,
            "meta": {
                "gameplay_tags": list(context.get("gameplay_tags", [])),
            },
        },
        "lodGroup": _lod_nodes(context),
        "sockets": _socket_nodes(context),
        "pivots": _pivot_nodes(context),
        "collision": _collision_nodes(context),
        "materials": [
            {"id": mat.get("id"), "displayName": mat.get("display_name") or mat.get("id")}
            for mat in context.get("materials", [])
            if isinstance(mat, dict) and mat.get("id")
        ],
        "surfaceMaterialSemantics": context.get("surface_material_semantics") or {},
        "textures": list(context.get("textures") or []),
        "textureConventions": context.get("texture_conventions") or {},
        "latheConstructionProvenance": context.get("construction_provenance") or {},
        "latheRuntimeSemantics": _runtime_semantics_godot(semantics),
        "latheRuntimeSemanticsTres": _runtime_semantics_tres(semantics, asset_name),
    }
    return json.dumps(root, indent=2, sort_keys=False)


def _runtime_semantics_godot(semantics: dict[str, Any] | None) -> dict[str, Any]:
    if semantics is None:
        return {}
    systems_out: dict[str, dict[str, Any]] = {}
    active_names: list[str] = []
    for system in semantics["systems"]:
        name = system["name"]
        if system["active"]:
            active_names.append(name)
        entry: dict[str, Any] = {
            "Active": system["active"],
            "ActiveFields": list(system["active_fields"]),
            "Counts": dict(system["counts"]),
            "Ids": {field: list(values) for field, values in system["ids"].items()},
        }
        if system["source"] is not None:
            entry["Source"] = system["source"]
        if system["schema"] is not None:
            entry["IrSchema"] = system["schema"]
        systems_out[name] = entry
    return {
        "Schema": semantics["schema"],
        "ActiveSystems": active_names,
        "Systems": systems_out,
    }


def _runtime_semantics_tres(
    semantics: dict[str, Any] | None, asset_name: str
) -> str:
    """Inline Godot ``.tres`` representation of the runtime_semantics block.

    Emits a hand-formatted Godot 4 text resource: a top-level ``Resource``
    with PascalCase properties and per-system ``SubResource`` blocks. The
    string is suitable for ``ResourceLoader.load_threaded_request`` once
    written to ``<asset>.lathe_runtime.tres`` by the EditorImportPlugin.
    """
    lines: list[str] = []
    lines.append("# Generated by Lathe v0.1 - runtime_semantics_v1")
    if semantics is None:
        lines.append('[gd_resource type="Resource" format=3]')
        lines.append("")
        lines.append("[resource]")
        lines.append('Schema = ""')
        lines.append("ActiveSystems = []")
        lines.append("Systems = {}")
        return "\n".join(lines) + "\n"

    systems = semantics["systems"]
    load_steps = len(systems) + 1
    lines.append(
        f'[gd_resource type="Resource" load_steps={load_steps} format=3]'
    )
    lines.append("")

    for index, system in enumerate(systems, start=1):
        lines.append(f'[sub_resource type="Resource" id="System_{index}"]')
        lines.append(f'Name = "{_tres_escape(system["name"])}"')
        lines.append(f"Active = {_tres_bool(system['active'])}")
        if system["source"] is not None:
            lines.append(f'Source = "{_tres_escape(system["source"])}"')
        if system["schema"] is not None:
            lines.append(f'IrSchema = "{_tres_escape(system["schema"])}"')
        lines.append(
            "ActiveFields = " + _tres_string_array(system["active_fields"])
        )
        lines.append("Counts = " + _tres_int_dict(system["counts"]))
        lines.append("Ids = " + _tres_string_list_dict(system["ids"]))
        lines.append("")

    lines.append("[resource]")
    lines.append(f'AssetName = "{_tres_escape(asset_name)}"')
    lines.append(f'Schema = "{_tres_escape(semantics["schema"])}"')
    active_names = [s["name"] for s in systems if s["active"]]
    lines.append("ActiveSystems = " + _tres_string_array(active_names))
    if systems:
        refs = ", ".join(
            f'"{s["name"]}": SubResource("System_{i}")'
            for i, s in enumerate(systems, start=1)
        )
        lines.append("Systems = {" + refs + "}")
    else:
        lines.append("Systems = {}")
    return "\n".join(lines) + "\n"


def _tres_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def _tres_bool(value: bool) -> str:
    return "true" if value else "false"


def _tres_string_array(values: list[str]) -> str:
    if not values:
        return "[]"
    inner = ", ".join(f'"{_tres_escape(v)}"' for v in values)
    return "[" + inner + "]"


def _tres_int_dict(values: dict[str, int]) -> str:
    if not values:
        return "{}"
    inner = ", ".join(
        f'"{_tres_escape(k)}": {int(v)}' for k, v in values.items()
    )
    return "{" + inner + "}"


def _tres_string_list_dict(values: dict[str, list[str]]) -> str:
    if not values:
        return "{}"
    inner = ", ".join(
        f'"{_tres_escape(k)}": {_tres_string_array(v)}'
        for k, v in values.items()
    )
    return "{" + inner + "}"


def _lod_nodes(context: dict[str, Any]) -> list[dict[str, Any]]:
    nodes: list[dict[str, Any]] = []
    for lod in context.get("lods", []):
        if not isinstance(lod, dict):
            continue
        nodes.append(
            {
                "type": "MeshInstance3D",
                "name": f"LOD{lod.get('level', 0)}",
                "meshUri": lod.get("mesh_uri"),
                "visibilityRangeBegin": float(lod.get("distance_min", 0.0) or 0.0),
                "visibilityRangeEnd": (
                    None if lod.get("distance_max") is None else float(lod.get("distance_max"))
                ),
                "screenCoverage": (
                    None if lod.get("screen_coverage") is None else float(lod.get("screen_coverage"))
                ),
                "triangleCount": int(lod.get("triangle_count") or 0),
            }
        )
    return nodes


def _socket_nodes(context: dict[str, Any]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for sock in context.get("sockets", []):
        if not isinstance(sock, dict) or not sock.get("id"):
            continue
        out.append(
            {
                "type": "Marker3D",
                "name": f"socket_{sock['id']}",
                "origin": list(sock.get("origin", [0.0, 0.0, 0.0])),
                "axis": list(sock.get("axis", [0.0, 1.0, 0.0])),
                "meta": {
                    "anchor_id": sock["id"],
                    "socket_type": sock.get("socket_type") or sock.get("kind") or "attach",
                    "parent_part_id": sock.get("parent_part_id"),
                },
            }
        )
    return out


def _pivot_nodes(context: dict[str, Any]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for piv in context.get("pivots", []):
        if not isinstance(piv, dict) or not piv.get("id"):
            continue
        out.append(
            {
                "type": "Marker3D",
                "name": f"pivot_{piv['id']}",
                "origin": list(piv.get("origin", [0.0, 0.0, 0.0])),
                "axis": list(piv.get("axis", [0.0, 1.0, 0.0])),
                "meta": {
                    "anchor_id": piv["id"],
                    "pivot_type": piv.get("pivot_type") or "center",
                },
            }
        )
    return out


def _collision_nodes(context: dict[str, Any]) -> dict[str, Any]:
    collisions = context.get("collisions", [])
    shapes: list[dict[str, Any]] = []
    for col in collisions:
        if not isinstance(col, dict):
            continue
        shapes.append(
            {
                "type": "CollisionShape3D",
                "name": f"shape_{col.get('id', 'hull')}",
                "shape": col.get("kind", "hull"),
                "meshUri": col.get("uri"),
                "parentPartId": col.get("parent_part_id"),
            }
        )
    return {
        "type": "StaticBody3D",
        "name": "collision",
        "shapes": shapes,
    }
