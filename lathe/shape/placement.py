# ---------------------------------------------------------------------
# RelationResolver — exhaustive candidate + hard reject + soft score.
# ---------------------------------------------------------------------


def _vec_dot(a: tuple[float, float, float], b: tuple[float, float, float]) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _vec_neg(a: tuple[float, float, float]) -> tuple[float, float, float]:
    return (-a[0], -a[1], -a[2])


def _normal_match(
    source_normal: tuple[float, float, float],
    target_normal: tuple[float, float, float],
    policy: str,
) -> tuple[bool, float]:
    """Return (match, dot) per normal policy.

    ``opposed``: source normal should be antiparallel to target normal.
    ``aligned``: parallel.
    ``any``: trivially matches.
    """
    if policy == "any":
        return True, 1.0
    dot = _vec_dot(source_normal, target_normal)
    if policy == "opposed":
        return dot < -0.5, -dot
    if policy == "aligned":
        return dot > 0.5, dot
    return False, 0.0


class RelationResolver:
    """Resolves a construction-graph edge into an authoritative placement.

    The resolver implements the §2 canonical order:

      1. exhaustive candidate generation
      2. hard constraint rejection (affordance match, normal policy,
         clearance/penetration bounds)
      3. soft constraint scoring
      4. deterministic tie-break (by candidate index)

    Beam search is intentionally *not* used at the asset level — it
    belongs at scene/world scale.
    """

    def __init__(self, relation_specs: Mapping[str, RelationSpec] | None = None) -> None:
        self._specs = dict(relation_specs) if relation_specs is not None else dict(RELATION_SPECS)

    def resolve(
        self,
        edge_id: str,
        relation: str,
        source_node_id: str,
        target_node_id: str,
        source_anchors: Iterable[Anchor],
        target_anchors: Iterable[Anchor],
    ) -> PlacementBinding:
        spec = self._specs.get(relation)
        if spec is None:
            return PlacementBinding(
                edge_id=edge_id,
                relation=relation,
                source_node_id=source_node_id,
                target_node_id=target_node_id,
                candidates=(),
                chosen=None,
                proof=f"no_relation_spec_for {relation!r}",
            )

        candidates: list[PlacementCandidate] = []
        source_list = list(source_anchors)
        target_list = list(target_anchors)

        for s in source_list:
            for t in target_list:
                # Hard reject: affordance match
                if spec.required_source_affordance not in s.affordances:
                    candidates.append(
                        PlacementCandidate(
                            edge_id=edge_id,
                            source_anchor_id=s.anchor_id,
                            target_anchor_id=t.anchor_id,
                            transform_world_cm=(0.0, 0.0, 0.0),
                            orientation_index=0,
                            constraint_residual_cm=0.0,
                            valid=False,
                            rejection_reason=f"source missing affordance {spec.required_source_affordance!r}",
                        )
                    )
                    continue
                if spec.required_target_affordance not in t.affordances:
                    candidates.append(
                        PlacementCandidate(
                            edge_id=edge_id,
                            source_anchor_id=s.anchor_id,
                            target_anchor_id=t.anchor_id,
                            transform_world_cm=(0.0, 0.0, 0.0),
                            orientation_index=0,
                            constraint_residual_cm=0.0,
                            valid=False,
                            rejection_reason=f"target missing affordance {spec.required_target_affordance!r}",
                        )
                    )
                    continue

                # Try each orientation candidate (4 = quarter-turns).
                # Source anchor's normal already points "into the host"
                # (the direction the source's mounting face is looking
                # toward, away from the source's own body). For
                # ``opposed`` policy: source.z and target.z are
                # antiparallel — they face each other.
                for orientation in range(spec.orientation_candidates):
                    source_normal = s.frame.normal()
                    target_normal = t.frame.normal()
                    matched, score = _normal_match(source_normal, target_normal, spec.normal_policy)
                    if not matched:
                        candidates.append(
                            PlacementCandidate(
                                edge_id=edge_id,
                                source_anchor_id=s.anchor_id,
                                target_anchor_id=t.anchor_id,
                                transform_world_cm=(0.0, 0.0, 0.0),
                                orientation_index=orientation,
                                constraint_residual_cm=0.0,
                                valid=False,
                                rejection_reason=f"normal_policy {spec.normal_policy!r} unsatisfied",
                                score=score,
                            )
                        )
                        continue

                    # Transform: target anchor origin + clearance offset
                    # along the target normal (positive = standoff).
                    transform = (
                        t.frame.origin_cm[0] + target_normal[0] * spec.clearance_cm,
                        t.frame.origin_cm[1] + target_normal[1] * spec.clearance_cm,
                        t.frame.origin_cm[2] + target_normal[2] * spec.clearance_cm,
                    )
                    candidates.append(
                        PlacementCandidate(
                            edge_id=edge_id,
                            source_anchor_id=s.anchor_id,
                            target_anchor_id=t.anchor_id,
                            transform_world_cm=transform,
                            orientation_index=orientation,
                            constraint_residual_cm=abs(spec.clearance_cm),
                            valid=True,
                            score=score,
                        )
                    )

        # Deterministic tie-break: highest score, then lowest candidate index.
        valid = [c for c in candidates if c.valid]
        if not valid:
            reason = (
                f"no_valid_candidate ({len(candidates)} considered, "
                f"{len(source_list)} src anchors, {len(target_list)} tgt anchors)"
            )
            return PlacementBinding(
                edge_id=edge_id,
                relation=relation,
                source_node_id=source_node_id,
                target_node_id=target_node_id,
                candidates=tuple(candidates),
                chosen=None,
                proof=reason,
            )

        # Sort by (-score, source_anchor_id, target_anchor_id, orientation)
        # for deterministic tie-break.
        valid_sorted = sorted(
            valid,
            key=lambda c: (
                -c.score,
                c.source_anchor_id,
                c.target_anchor_id,
                c.orientation_index,
            ),
        )
        chosen = valid_sorted[0]
        proof = (
            f"chose {chosen.source_anchor_id} → {chosen.target_anchor_id} "
            f"orient={chosen.orientation_index} score={chosen.score:.3f} "
            f"clearance={chosen.constraint_residual_cm:.3f}cm "
            f"(out of {len(valid)} valid / {len(candidates)} total)"
        )
        return PlacementBinding(
            edge_id=edge_id,
            relation=relation,
            source_node_id=source_node_id,
            target_node_id=target_node_id,
            candidates=tuple(candidates),
            chosen=chosen,
            proof=proof,
        )


