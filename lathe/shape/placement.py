"""``lathe.shape.placement_binding_v1`` — relation resolver substrate.

Replaces name-suffix heuristics with a typed anchor/scope/constraint
system. Stage 6's role becomes: take typed construction-graph edges
(``attached_to``, ``inset_into``, ``wraps_around``, ``aligned_with``,
``mirrors``, ``supports``, ``cuts``) and resolve them into authoritative
transforms + cuts + proof.

Per ``docs/research/newresearch.md`` §2:

    Semantic relation:    metal_corner_guard attaches_to crate.corner[NE]
    Numeric realization:  resolve host anchor frame -> choose orientation
                          -> apply offsets/clearances -> validate
                          collision/support -> emit transform

This module is the contract surface. Per-NODE_TYPE anchor emitters live
in ``lathe/asset_quality/procedural_synthesizer/anchors/``. Generators
read ``PlacementBinding.chosen.transform`` to position their primitives
instead of heuristic name-suffix lookups.
"""

from __future__ import annotations

import math
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any

CONTRACT_VERSION = "lathe.shape.placement_binding_v1"


# ---------------------------------------------------------------------
# Anchor — a labeled local frame on a host node with role + affordances.
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class Frame:
    """Right-handed local frame: origin + 3 orthonormal axes."""

    origin_cm: tuple[float, float, float] = (0.0, 0.0, 0.0)
    x_axis: tuple[float, float, float] = (1.0, 0.0, 0.0)
    y_axis: tuple[float, float, float] = (0.0, 1.0, 0.0)
    z_axis: tuple[float, float, float] = (0.0, 0.0, 1.0)

    def normal(self) -> tuple[float, float, float]:
        """The frame's primary normal — taken as the Z axis."""
        return self.z_axis


@dataclass(frozen=True)
class Anchor:
    """A typed attachment point on a host node.

    Carries enough information for a relation resolver to evaluate
    compatibility with a candidate source anchor: a labeled role, a
    local frame, a bounding region in which contact is permitted, an
    affordance set (what relations the anchor admits), and a capacity
    (how many source features may dock simultaneously).
    """

    anchor_id: str
    role: str
    frame: Frame
    bounds_cm: tuple[float, float, float] = (10.0, 10.0, 10.0)
    affordances: tuple[str, ...] = ()
    capacity: int = 1
    host_node_id: str = ""
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class Scope:
    """A region/scope associated with a construction-graph node.

    Scopes are the unit a placement candidate lives in: a "front face"
    scope on a primary_volume node has an extent + parent frame and is
    the host of multiple anchors (corner, edge, center).
    """

    scope_id: str
    owner_node_id: str
    parent_frame: Frame
    local_bbox_cm: tuple[float, float, float]
    affordances: tuple[str, ...] = ()


@dataclass(frozen=True)
class PlacementCandidate:
    """A proposed source→target anchor pair with computed transform.

    Generated by ``RelationResolver`` during exhaustive candidate
    enumeration. Carries an explicit rejection reason when a hard
    constraint excludes it so traces remain inspectable.
    """

    edge_id: str
    source_anchor_id: str
    target_anchor_id: str
    transform_world_cm: tuple[float, float, float]
    orientation_index: int
    constraint_residual_cm: float
    valid: bool
    rejection_reason: str = ""
    score: float = 0.0


@dataclass(frozen=True)
class PlacementBinding:
    """The final resolved placement for one construction-graph edge.

    Holds the full candidate list (for trace/debug), the chosen
    candidate, and a textual proof line describing why it was chosen.
    """

    edge_id: str
    relation: str
    source_node_id: str
    target_node_id: str
    candidates: tuple[PlacementCandidate, ...]
    chosen: PlacementCandidate | None
    proof: str

    def is_resolved(self) -> bool:
        return self.chosen is not None and self.chosen.valid


# ---------------------------------------------------------------------
# Relation specs — declarative contract per relation type.
# ---------------------------------------------------------------------


@dataclass(frozen=True)
class RelationSpec:
    """Declarative contract for one relation type.

    - ``required_source_affordance``: source anchor must declare this
      affordance to be a candidate.
    - ``required_target_affordance``: target anchor must declare this.
    - ``normal_policy``: ``"opposed"`` (face-to-face contact),
      ``"aligned"`` (same direction), ``"any"``.
    - ``clearance_cm`` / ``allow_penetration_cm``: geometric tolerances
      the resolver enforces on the chosen pair.
    - ``orientation_candidates``: how many rotational variants the
      resolver tries (4 = quarter-turns, 1 = single orientation).
    - ``support_required``: whether the resolver should reject
      placements where the support invariant cannot be proven.
    """

    relation: str
    required_source_affordance: str
    required_target_affordance: str
    normal_policy: str = "opposed"
    clearance_cm: float = 0.2
    allow_penetration_cm: float = 0.05
    orientation_candidates: int = 4
    support_required: bool = False


