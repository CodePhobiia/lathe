def test_scene_source_bridge_cli_roundtrips_exact_payload(tmp_path: Path) -> None:
    source_path = tmp_path / "scene.lth"
    roundtrip_path = tmp_path / "scene_graph.roundtrip.json"

    to_source = _cli("scene", "scene-graph-to-source", str(EXAMPLE_SCENE), "--out", str(source_path))

    assert to_source.returncode == 0, to_source.stderr
    to_source_payload = json.loads(to_source.stdout)
    assert to_source_payload["ok"] is True
    assert to_source_payload["command"] == "scene.scene-graph-to-source"
    assert [diagnostic["code"] for diagnostic in to_source_payload["diagnostics"]] == ["SS2001"]
    assert to_source_payload["diagnostics"][0]["severity"] == "warning"
    assert source_path.exists()

    to_graph = _cli("scene", "source-to-scene-graph", str(source_path), "--out", str(roundtrip_path))

    assert to_graph.returncode == 0, to_graph.stderr
    to_graph_payload = json.loads(to_graph.stdout)
    assert to_graph_payload["ok"] is True
    assert to_graph_payload["command"] == "scene.source-to-scene-graph"
    assert json.loads(roundtrip_path.read_text(encoding="utf-8")) == _scene()


def test_scene_source_bridge_cli_reports_unsupported_source(tmp_path: Path) -> None:
    source_path = tmp_path / "hand_authored_scene.lth"
    out_path = tmp_path / "scene_graph.json"
    source_path.write_text("scene hand_authored_scene {\n  version = 1\n}\n", encoding="utf-8")

    result = _cli("scene", "source-to-scene-graph", str(source_path), "--out", str(out_path))

    assert result.returncode == 1
    assert result.stderr == ""
    payload = json.loads(result.stdout)
    assert payload["ok"] is False
    assert payload["diagnostics"][0]["code"] == "SS1002"
    assert not out_path.exists()


def test_scene_source_bridge_cli_reports_missing_source_as_json(tmp_path: Path) -> None:
    source_path = tmp_path / "missing_scene.lth"
    out_path = tmp_path / "scene_graph.json"

    result = _cli("scene", "source-to-scene-graph", str(source_path), "--out", str(out_path))

    assert result.returncode == 1
    assert result.stderr == ""
    payload = json.loads(result.stdout)
    assert payload["ok"] is False
    assert payload["diagnostics"][0]["code"] == "SS1900"
    assert not out_path.exists()


def test_model_facing_good_outputs_validate_and_stay_in_sync() -> None:
    scene_graph = json.loads(GOOD_SCENE.read_text(encoding="utf-8"))
    source_text = GOOD_SOURCE.read_text(encoding="utf-8")

    parsed, diagnostics = source_to_scene_graph(
        source_text,
        root=GOOD_OUTPUTS,
        source_path=GOOD_SOURCE,
    )

    assert diagnostics == []
    assert parsed == scene_graph
    assert scene_graph_to_source(scene_graph) == source_text
    bridge_diagnostics = scene_graph_to_source_diagnostics(scene_graph)
    assert [diagnostic["code"] for diagnostic in bridge_diagnostics] == ["SS2001"]
