def test_materialize_scene_assets_can_build_generated_sources(tmp_path: Path, monkeypatch) -> None:
    calls: list[tuple[str, Path]] = []

    def fake_build_asset(program, asset_name, out_dir, runtime_config=None, execution_profile_override=None):
        del program, runtime_config, execution_profile_override
        build_dir = Path(out_dir)
        build_dir.mkdir(parents=True, exist_ok=True)
        report = {
            "asset": asset_name,
            "certified": True,
            "score": 0.95,
            "threshold": 0.8,
            "diagnostics": [],
        }
        (build_dir / "build_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
        calls.append((asset_name, build_dir))
        return report

    monkeypatch.setattr("lathe.scene.materialize._run_build_asset", fake_build_asset)

    payload = materialize_scene_assets(EXAMPLE_SCENE, tmp_path / "materialized", build_assets=True)

    manifest = payload["manifest"]
    assert payload["ok"] is True
    assert validate_scene_materialization_manifest_payload(manifest) == []
    assert manifest["summary"]["builds_requested"] == len(manifest["asset_sources"])
    assert manifest["summary"]["builds_succeeded"] == len(manifest["asset_sources"])
    assert manifest["summary"]["builds_failed"] == 0
    assert len(calls) == len(manifest["asset_sources"])
    for entry in manifest["asset_sources"]:
        assert entry["build"]["requested"] is True
        assert entry["build"]["ok"] is True
        assert entry["build"]["report_path"] == f"builds/{entry['asset_name']}/build_report.json"
        metadata = json.loads((tmp_path / "materialized" / entry["metadata_path"]).read_text(encoding="utf-8"))
        assert metadata["build"] == entry["build"]


def test_materialize_scene_assets_records_build_failures(tmp_path: Path, monkeypatch) -> None:
    def fake_build_asset(program, asset_name, out_dir, runtime_config=None, execution_profile_override=None):
        del program, out_dir, runtime_config, execution_profile_override
        raise BuildError(
            "Validation failed",
            diagnostics=[
                {
                    "code": "L6401",
                    "name": "visual_surface_authoring_quality_failed",
                    "severity": "error",
                    "phase": "validate",
                    "asset": asset_name,
                    "message": "Surface authoring quality is below threshold.",
                }
            ],
        )

    monkeypatch.setattr("lathe.scene.materialize._run_build_asset", fake_build_asset)

    payload = materialize_scene_assets(EXAMPLE_SCENE, tmp_path / "materialized", build_assets=True)

    manifest = payload["manifest"]
    assert payload["ok"] is False
    assert validate_scene_materialization_manifest_payload(manifest) == []
    assert manifest["summary"]["builds_requested"] == len(manifest["asset_sources"])
    assert manifest["summary"]["builds_succeeded"] == 0
    assert manifest["summary"]["builds_failed"] == len(manifest["asset_sources"])
    assert len(payload["diagnostics"]) == len(manifest["asset_sources"])
    assert all(entry["build"]["ok"] is False for entry in manifest["asset_sources"])
    assert all(diagnostic["path"] for diagnostic in payload["diagnostics"])


def test_scene_materialize_cli_emits_schema_valid_manifest(tmp_path: Path) -> None:
    out_dir = tmp_path / "materialize_cli"

    result = _cli("scene", "materialize", str(EXAMPLE_SCENE), "--out", str(out_dir))

    assert result.returncode == 0, result.stderr or result.stdout
    payload = json.loads(result.stdout)
    assert payload["ok"] is True
    assert payload["command"] == "scene.materialize"
    assert payload["contract"] == "scene_materialization_manifest"
    expected_out = out_dir.relative_to(REPO_ROOT).as_posix() if out_dir.is_relative_to(REPO_ROOT) else str(out_dir)
    assert payload["out"] == expected_out
    manifest_path = out_dir / "scene_materialization_manifest.json"
    assert manifest_path.is_file()

    validate_result = _cli("wonder", "validate-scene-materialization-manifest", str(manifest_path))

    assert validate_result.returncode == 0, validate_result.stderr or validate_result.stdout
    assert json.loads(validate_result.stdout)["ok"] is True
