from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

from lathe.errors import BuildError
from lathe.scene.materialize import materialize_scene_assets, validate_scene_materialization_manifest_payload

REPO_ROOT = Path(__file__).resolve().parents[2]
EXAMPLE_DIR = REPO_ROOT / "examples" / "wonder" / "alchemist_observatory"
EXAMPLE_SCENE = EXAMPLE_DIR / "scene_graph.json"


def _cli(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "lathe.cli", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        check=False,
    )


def _write_json(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def _scene() -> dict:
    return json.loads(EXAMPLE_SCENE.read_text(encoding="utf-8"))


def test_materialize_scene_assets_writes_checkable_asset_sources(tmp_path: Path) -> None:
    out_dir = tmp_path / "materialized"

    payload = materialize_scene_assets(EXAMPLE_SCENE, out_dir)

    assert payload["ok"] is True
    manifest = payload["manifest"]
    assert validate_scene_materialization_manifest_payload(manifest) == []
    assert manifest["schema_version"] == "lathe.scene_materialization_manifest.v1"
    assert manifest["summary"]["source_files"] == len(manifest["asset_sources"])
    assert manifest["summary"]["checker_errors"] == 0
    assert manifest["summary"]["planner_errors"] == 0
    assert manifest["summary"]["builds_requested"] == 0
    assert manifest["summary"]["builds_succeeded"] == 0
    assert manifest["summary"]["builds_failed"] == 0
    assert {entry["asset_kind"] for entry in manifest["asset_sources"]} >= {
        "hard_surface_prop",
        "env_module",
        "mechanical_assembly",
    }

    for entry in manifest["asset_sources"]:
        source_path = out_dir / entry["source_path"]
        metadata_path = out_dir / entry["metadata_path"]
        assert source_path.is_file()
        assert metadata_path.is_file()
        source_text = source_path.read_text(encoding="utf-8")
        assert "Generated by Lathe lathe.scene_materialization_manifest.v1" in source_text
        assert "material " in source_text
        assert entry["source_path"].startswith("assets/")
        assert ".." not in entry["source_path"].split("/")
        assert entry["check"]["ok"] is True
        assert entry["plan"]["ok"] is True

        check_result = _cli("check", str(source_path))
        assert check_result.returncode == 0, check_result.stderr or check_result.stdout

        plan_result = _cli("plan", str(source_path), entry["asset_name"])
        assert plan_result.returncode == 0, plan_result.stderr or plan_result.stdout


def test_materialize_scene_assets_groups_repeated_instance_friendly_sources(tmp_path: Path) -> None:
    scene = _scene()
    candle = next(item for item in scene["objects"] if item["lathe_asset"] == "candle_cluster")
    second_candle = json.loads(json.dumps(candle))
    second_candle["object_id"] = "obj_candle_cluster_002"
    second_candle["name"] = "Second Candle Cluster"
    second_candle["transform"]["position"] = [-2.0, 1.1, 0.1]
    scene["objects"].append(second_candle)
    scene_path = tmp_path / "repeated_candles_scene_graph.json"
    _write_json(scene_path, scene)

    payload = materialize_scene_assets(scene_path, tmp_path / "materialized")

    manifest = payload["manifest"]
    assert validate_scene_materialization_manifest_payload(manifest) == []
    candle_entries = [
        entry for entry in manifest["asset_sources"] if entry["source"].get("ref") == "candle_cluster"
    ]
    assert len(candle_entries) == 1
    assert candle_entries[0]["object_ids"] == ["obj_candle_cluster_001", "obj_candle_cluster_002"]
    assert candle_entries[0]["instancing"]["instance_friendly"] is True
    assert candle_entries[0]["instancing"]["object_count"] == 2
    assert candle_entries[0]["instancing"]["requires_unique_build"] is False


def test_materialize_scene_assets_preserves_valid_source_scene_id(tmp_path: Path) -> None:
    scene = _scene()
    scene["scene_id"] = "scene_" + ("a" * 73)
    scene_path = tmp_path / "long_scene_id_scene_graph.json"
    _write_json(scene_path, scene)

    payload = materialize_scene_assets(scene_path, tmp_path / "materialized")

    manifest = payload["manifest"]
    assert validate_scene_materialization_manifest_payload(manifest) == []
    assert manifest["scene_id"] == scene["scene_id"]
    metadata_path = tmp_path / "materialized" / manifest["asset_sources"][0]["metadata_path"]
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    assert metadata["scene_id"] == scene["scene_id"]
    source_path = tmp_path / "materialized" / manifest["asset_sources"][0]["source_path"]
    assert f"// Source scene: {scene['scene_id']}." in source_path.read_text(encoding="utf-8")


