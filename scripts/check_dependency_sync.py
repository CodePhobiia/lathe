"""Verify dependency lock and exported requirements files are in sync."""

from __future__ import annotations

import difflib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# This file was autogenerated by uv via the following command:"
EXPORTS = (
    (
        "requirements.txt",
        ("uv", "export", "--format", "requirements-txt", "--all-extras"),
        "uv export --format requirements-txt --all-extras -o requirements.txt",
    ),
    (
        "requirements-dev.txt",
        ("uv", "export", "--format", "requirements-txt", "--group", "dev"),
        "uv export --format requirements-txt --group dev -o requirements-dev.txt",
    ),
)
MAX_DIFF_LINES = 120


def _run(command: tuple[str, ...]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        cwd=ROOT,
        check=False,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )


def _normalized_body(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines()[2:]


def _check_export(filename: str, base_command: tuple[str, ...], expected_header_command: str) -> bool:
    checked_in = ROOT / filename
    lines = checked_in.read_text(encoding="utf-8").splitlines()
    expected_header = [HEADER, f"#    {expected_header_command}"]
    if lines[:2] != expected_header:
        print(f"{filename}: header does not match the canonical uv export command", file=sys.stderr)
        print(f"expected: {expected_header[1]}", file=sys.stderr)
        return False

    with tempfile.TemporaryDirectory(prefix="lathe-deps-") as temp_dir:
        generated = Path(temp_dir) / filename
        result = _run((*base_command, "-o", str(generated)))
        if result.returncode != 0:
            print(result.stdout, file=sys.stderr)
            return False

        expected = _normalized_body(checked_in)
        actual = _normalized_body(generated)
        if expected == actual:
            print(f"{filename}: ok")
            return True

        print(
            f"{filename}: stale export; run `{expected_header_command}`",
            file=sys.stderr,
        )
        diff = difflib.unified_diff(
            expected,
            actual,
            fromfile=filename,
            tofile=f"generated/{filename}",
            lineterm="",
        )
        for index, line in enumerate(diff):
            if index >= MAX_DIFF_LINES:
                print("... diff truncated ...", file=sys.stderr)
                break
            print(line, file=sys.stderr)
        return False


def main() -> int:
    """Verify uv.lock and exported requirements files agree."""
    if shutil.which("uv") is None:
        print("uv is required to verify dependency sync", file=sys.stderr)
        return 2

    lock_check = _run(("uv", "lock", "--check"))
    if lock_check.returncode != 0:
        print(lock_check.stdout, file=sys.stderr)
        return lock_check.returncode
    print("uv.lock: ok")

    ok = True
    for filename, command, expected_header_command in EXPORTS:
        ok = _check_export(filename, command, expected_header_command) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
