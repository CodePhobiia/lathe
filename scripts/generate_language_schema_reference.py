"""Generate language and normalized schema reference docs.

The generated pages are intentionally derived from the public grammar,
JSON Schema, and normalizer defaults so documentation drift is visible in
unit tests.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from lathe.defaults import (
    ASSET_DEFAULTS,
    ASSET_PACKAGE_DEFAULTS,
    ASSET_PUBLISH_DEFAULTS,
    ASSET_REPAIR_POLICY_DEFAULTS,
    ASSET_SOURCE_SURFACE_DEFAULTS,
    ASSET_VALIDATE_DEFAULTS,
    BUILD_STAGE_DEFAULTS,
    PROGRAM_DEFAULTS,
    SPACE_DEFAULTS,
    TOP_LEVEL_REPAIR_POLICY_DEFAULTS,
    VALIDATE_REPAIR_DEFAULTS,
)

ROOT = Path(__file__).resolve().parents[1]
GRAMMAR_PATH = ROOT / "grammar" / "lathe.lark"
SCHEMA_PATH = ROOT / "schema" / "lathe.schema.json"
LANGUAGE_OUTPUT_PATH = ROOT / "docs" / "language_reference.md"
SCHEMA_OUTPUT_PATH = ROOT / "docs" / "schema_reference.md"

GENERATED_NOTICE = "<!-- Generated by scripts/generate_language_schema_reference.py; do not edit by hand. -->"


def _read_grammar() -> str:
    return GRAMMAR_PATH.read_text(encoding="utf-8")


def _read_schema() -> dict[str, Any]:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


def _extract_decl_rules(grammar: str) -> list[str]:
    match = re.search(r"(?ms)^\?decl:(.*?)(?:\n\n)", grammar)
    if match is None:
        raise RuntimeError("Could not find ?decl block in grammar/lathe.lark")
    seen: set[str] = set()
    decls: list[str] = []
    for rule in re.findall(r"\b([a-z_]+_decl)\b", match.group(1)):
        if rule not in seen:
            seen.add(rule)
            decls.append(rule)
    return decls


def _extract_rule_keywords(grammar: str) -> dict[str, str]:
    return dict(re.findall(r'(?m)^([a-z_]+):\s+"([^"]+)"', grammar))


def _extract_rule_line(grammar: str, rule_name: str) -> str:
    match = re.search(rf"(?m)^{re.escape(rule_name)}:([^\n]+)", grammar)
    if match is None:
        raise RuntimeError(f"Could not find {rule_name} rule in grammar/lathe.lark")
    return match.group(1)


def _program_field_for_keyword(keyword: str) -> str:
    overrides = {
        "assembly": "assemblies",
        "benchmark": "benchmarks",
        "fixture": "fixtures",
        "import": "imports",
        "module": "module",
        "space": "spaces",
        "test": "tests",
    }
    if keyword in overrides:
        return overrides[keyword]
    if keyword.endswith("y"):
        return f"{keyword[:-1]}ies"
    return f"{keyword}s"


def _schema_ref_name(node: Mapping[str, Any]) -> str:
    ref = node.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    return ""


def _schema_type_summary(node: Mapping[str, Any]) -> str:
    if "$ref" in node:
        return _schema_ref_name(node)
    node_type = node.get("type")
    if node_type == "array":
        items = node.get("items", {})
        if isinstance(items, Mapping) and "$ref" in items:
            return f"array<{_schema_ref_name(items)}>"
        if isinstance(items, Mapping) and "type" in items:
            return f"array<{items['type']}>"
        return "array"
    if isinstance(node_type, list):
        return " or ".join(str(item) for item in node_type)
    if isinstance(node_type, str):
        return node_type
    if "const" in node:
        return f"const {node['const']}"
    if "anyOf" in node:
        return "anyOf"
    return "object"


def _escape_table(value: object) -> str:
    text = str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def _format_value(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ": "))


def _table(headers: list[str], rows: Iterable[Iterable[object]]) -> list[str]:
    out = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        out.append("| " + " | ".join(_escape_table(cell) for cell in row) + " |")
    return out


def _flatten_defaults(prefix: str, value: Any) -> list[tuple[str, str]]:
    if isinstance(value, dict) and value:
        rows: list[tuple[str, str]] = []
        for key, child in value.items():
            rows.extend(_flatten_defaults(f"{prefix}.{key}" if prefix else key, child))
        return rows
    return [(prefix, _format_value(value))]


def _required(schema: Mapping[str, Any], name: str) -> str:
    return "yes" if name in schema.get("required", []) else "no"


def _collect_reference_model() -> dict[str, Any]:
    grammar = _read_grammar()
    schema = _read_schema()
    keywords_by_rule = _extract_rule_keywords(grammar)
    schema_properties = schema.get("properties", {})

    declarations = [
        {"source": "module", "rule": "module_decl", "field": "module"},
        {"source": "import", "rule": "import_decl", "field": "imports"},
    ]
    for rule in _extract_decl_rules(grammar):
        keyword = keywords_by_rule.get(rule)
        if keyword is None:
            raise RuntimeError(f"Could not infer source keyword for grammar rule {rule}")
        declarations.append(
            {
                "source": keyword,
                "rule": rule,
                "field": _program_field_for_keyword(keyword),
            }
        )

    missing_decl_fields = [item["field"] for item in declarations if item["field"] not in schema_properties]
    if missing_decl_fields:
        joined = ", ".join(missing_decl_fields)
        raise RuntimeError(f"Grammar declarations missing from normalized schema: {joined}")

    missing_default_fields = [field for field in PROGRAM_DEFAULTS if field not in schema_properties]
    if missing_default_fields:
        joined = ", ".join(missing_default_fields)
        raise RuntimeError(f"Program defaults missing from normalized schema: {joined}")

    block_keywords = _extract_rule_keywords(grammar)
    asset_block_rules = re.findall(r"\b([a-z_]+_block)\?", _extract_rule_line(grammar, "asset_decl"))
    asset_blocks = [
        {
            "source": block_keywords[rule],
            "rule": rule,
            "field": "space" if rule == "search_inline_block" else block_keywords[rule],
        }
        for rule in asset_block_rules
    ]
    asset_required = schema["$defs"]["asset"]["required"]
    missing_asset_fields = [
        item["field"]
        for item in asset_blocks
        if item["field"] != "search" and item["field"] not in asset_required
    ]
    if missing_asset_fields:
        joined = ", ".join(missing_asset_fields)
        raise RuntimeError(f"Asset grammar blocks missing from schema asset.required: {joined}")

    build_block_rules = re.findall(r"\b([a-z_]+_block)\?", _extract_rule_line(grammar, "build_block"))
    build_blocks = [{"source": block_keywords[rule], "rule": rule} for rule in build_block_rules]
    missing_build_defaults = [
        item["source"] for item in build_blocks if item["source"] not in BUILD_STAGE_DEFAULTS
    ]
    if missing_build_defaults:
        joined = ", ".join(missing_build_defaults)
        raise RuntimeError(f"Build grammar blocks missing from BUILD_STAGE_DEFAULTS: {joined}")

    return {
        "grammar": grammar,
        "schema": schema,
        "declarations": declarations,
        "asset_blocks": asset_blocks,
        "build_blocks": build_blocks,
    }


def render_language_reference() -> str:
    """Render the committed language reference from grammar/schema inputs."""
    model = _collect_reference_model()
    schema = model["schema"]

    declaration_rows = [
        [f"`{item['source']}`", f"`{item['rule']}`", f"`{item['field']}`"] for item in model["declarations"]
    ]
    asset_block_rows = [
        [f"`{item['source']}`", f"`{item['rule']}`", f"`{item['field']}`"] for item in model["asset_blocks"]
    ]
    build_block_rows = [
        [f"`{item['source']}`", f"`{item['rule']}`", f"`build.{item['source']}`"]
        for item in model["build_blocks"]
    ]

    units = schema["$defs"]["unit"]["properties"]["unit"]["enum"]
    kinds = schema["$defs"]["asset"]["properties"]["kind"]["enum"]

    sections = [
        "# Lathe Language Reference",
        "",
        GENERATED_NOTICE,
        "",
        "This reference is generated from `grammar/lathe.lark`, `schema/lathe.schema.json`, and "
        "`lathe/defaults.py`.",
        "",
        "## Source File Shape",
        "",
        "A source file has an optional `module`, zero or more `import` declarations, and then any "
        "number of public declarations. The text grammar is the parser contract; normalized JSON "
        "is validated by `schema/lathe.schema.json` after defaults are inserted.",
        "",
        "## Top-Level Declarations",
        "",
        *_table(["Source keyword", "Grammar rule", "Normalized field"], declaration_rows),
        "",
        "## Asset Declarations",
        "",
        "Asset headers use `asset <name>: <kind>`, with optional `from <qident>` and "
        "`uses <qident>, ...` clauses before the body.",
        "",
        "Supported asset kinds:",
        "",
        ", ".join(f"`{kind}`" for kind in kinds),
        "",
        "Asset body blocks are accepted in the grammar order below.",
        "",
        *_table(["Source block", "Grammar rule", "Normalized field"], asset_block_rows),
        "",
        "`search { ... }` is a source alias that normalizes into the same `space` field as `space { ... }`.",
        "",
        "## Build Blocks",
        "",
        "The `build` block exposes these stage blocks. Each stage has language defaults documented "
        "in `docs/schema_reference.md`.",
        "",
        *_table(["Source block", "Grammar rule", "Normalized field"], build_block_rows),
        "",
        "## Rules, Spaces, Tests, And Variants",
        "",
        "- Validation-style rules use `ensure <expr>` and `prefer <expr> weight <number>`.",
        "- Search spaces use `vary <path> in <expr>`, `freeze <path>`, "
        "`objective maximize|minimize <metric> weight <number>`, and `select best_of <number>`.",
        "- Tests and benchmarks contain assignments plus `assert <expr>` statements.",
        "- Variants use `set`, `append`, `remove`, and `unset` patches against dotted paths.",
        "",
        "## Expressions And Literals",
        "",
        "Identifiers match `[a-z][a-z0-9_]*`; qualified identifiers are dot-separated identifiers. "
        "Expressions support booleans, strings, numbers, unit literals, lists, calls, ranges, "
        "unary `not`/`-`, arithmetic, comparison, equality, `in`, `and`, and `or`.",
        "",
        "Supported unit suffixes:",
        "",
        ", ".join(f"`{unit}`" for unit in units),
        "",
    ]
    return "\n".join(sections)


def _render_root_schema_table(schema: Mapping[str, Any]) -> list[str]:
    properties = schema["properties"]
    rows = []
    for name in schema["required"]:
        node = properties[name]
        rows.append([f"`{name}`", _schema_type_summary(node), _required(schema, name)])
    return _table(["Field", "Schema type", "Required"], rows)


def _render_defs_table(schema: Mapping[str, Any]) -> list[str]:
    rows = []
    for name, node in schema["$defs"].items():
        required = ", ".join(f"`{field}`" for field in node.get("required", [])) or "-"
        additional = node.get("additionalProperties")
        additional_text = "not specified" if additional is None else f"`{_format_value(additional)}`"
        rows.append([f"`{name}`", required, additional_text])
    return _table(["Definition", "Required fields", "Additional properties"], rows)


def _render_default_table(title: str, defaults: Mapping[str, Any]) -> list[str]:
    rows = _flatten_defaults("", defaults)
    return [f"### {title}", "", *_table(["Path", "Default"], rows), ""]


def render_schema_reference() -> str:
    """Render the committed normalized AST schema reference."""
    model = _collect_reference_model()
    schema = model["schema"]

    build_default_rows: list[tuple[str, str]] = []
    for stage, defaults in BUILD_STAGE_DEFAULTS.items():
        build_default_rows.extend(_flatten_defaults(f"build.{stage}", defaults))

    sections = [
        "# Lathe Normalized AST Schema Reference",
        "",
        GENERATED_NOTICE,
        "",
        "This reference is generated from the committed normalized AST schema and canonical "
        "normalizer defaults.",
        "",
        "## Schema Identity",
        "",
        *_table(
            ["Property", "Value"],
            [
                ["`$schema`", schema.get("$schema", "")],
                ["`$id`", schema.get("$id", "")],
                ["`title`", schema.get("title", "")],
                ["Root additional properties", f"`{_format_value(schema.get('additionalProperties'))}`"],
            ],
        ),
        "",
        "## Root Object Fields",
        "",
        *_render_root_schema_table(schema),
        "",
        "Every root field above is required in normalized JSON. Missing source declarations "
        "normalize to empty arrays, and `module` normalizes to `null` when omitted.",
        "",
        "## Declaration Shapes",
        "",
        *_render_defs_table(schema),
        "",
        "## Public Defaults",
        "",
        *_render_default_table("Program Defaults", PROGRAM_DEFAULTS),
        *_render_default_table("Asset Defaults", ASSET_DEFAULTS),
        "### Build Stage Defaults",
        "",
        *_table(["Path", "Default"], build_default_rows),
        "",
        *_render_default_table("Source Surface Defaults", ASSET_SOURCE_SURFACE_DEFAULTS),
        *_render_default_table("Validate Defaults", ASSET_VALIDATE_DEFAULTS),
        *_render_default_table("Validate Repair Defaults", VALIDATE_REPAIR_DEFAULTS),
        *_render_default_table("Asset Repair Policy Defaults", ASSET_REPAIR_POLICY_DEFAULTS),
        *_render_default_table("Top-Level Repair Policy Defaults", TOP_LEVEL_REPAIR_POLICY_DEFAULTS),
        *_render_default_table("Space Defaults", SPACE_DEFAULTS),
        *_render_default_table("Package Defaults", ASSET_PACKAGE_DEFAULTS),
        *_render_default_table("Publish Defaults", ASSET_PUBLISH_DEFAULTS),
        "## Validation Rules Captured By The Schema",
        "",
        "- The root object has `additionalProperties: false`; unknown top-level fields are rejected.",
        "- Most normalized declaration shapes also set `additionalProperties: false`; "
        "`profile_like`, `asset`, `validate`, `repair_policy_spec`, `patch`, and a few "
        "intent-bearing maps intentionally allow extension fields.",
        "- `kind` is limited to `hard_surface_prop`, `env_module`, and `mechanical_assembly`.",
        "- Unit literals normalize to `{type, value, unit}` objects whose `unit` value is one of "
        "the grammar-supported unit suffixes.",
        "- Rule weights and space objective weights must be positive when present.",
        "- Top-level repair policies and validate repair specs require non-negative `max_rounds` "
        "when the field is present.",
        "",
    ]
    return "\n".join(sections)


def main() -> None:
    """Regenerate the committed language and schema reference files."""
    LANGUAGE_OUTPUT_PATH.write_text(render_language_reference(), encoding="utf-8", newline="\n")
    SCHEMA_OUTPUT_PATH.write_text(render_schema_reference(), encoding="utf-8", newline="\n")
    print(f"wrote {LANGUAGE_OUTPUT_PATH.relative_to(ROOT)}")
    print(f"wrote {SCHEMA_OUTPUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
