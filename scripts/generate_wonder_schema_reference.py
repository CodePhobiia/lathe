def _repo_path(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _load_schema(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _format_value(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ": "))


def _escape_table(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(headers: list[str], rows: Iterable[Iterable[object]]) -> list[str]:
    out = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        out.append("| " + " | ".join(_escape_table(cell) for cell in row) + " |")
    return out


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _type_summary(node: Mapping[str, Any]) -> str:
    ref = node.get("$ref")
    if isinstance(ref, str):
        return _ref_name(ref)

    if "const" in node:
        return f"const `{_format_value(node['const'])}`"

    if "enum" in node:
        return "enum"

    node_type = node.get("type")
    if node_type == "array":
        items = node.get("items", {})
        if isinstance(items, Mapping):
            return f"array<{_type_summary(items)}>"
        return "array"

    if isinstance(node_type, list):
        return " or ".join(str(item) for item in node_type)

    if isinstance(node_type, str):
        return node_type

    if "anyOf" in node:
        return "anyOf"

    return "object"


def _constraint_parts(node: Mapping[str, Any]) -> list[str]:
    parts: list[str] = []

    if "enum" in node:
        values = node["enum"]
        if isinstance(values, list):
            parts.append("values: " + ", ".join(f"`{_format_value(value)}`" for value in values))

    if "pattern" in node:
        parts.append(f"pattern `{node['pattern']}`")

    if "minLength" in node or "maxLength" in node:
        minimum = node.get("minLength", "-")
        maximum = node.get("maxLength", "-")
        parts.append(f"length {minimum}..{maximum}")

    if "minItems" in node or "maxItems" in node:
        minimum = node.get("minItems", "-")
        maximum = node.get("maxItems", "-")
        parts.append(f"items {minimum}..{maximum}")

    if node.get("uniqueItems") is True:
        parts.append("unique items")

    if "minimum" in node or "maximum" in node:
        minimum = node.get("minimum", "-")
        maximum = node.get("maximum", "-")
        parts.append(f"value {minimum}..{maximum}")

    if "exclusiveMinimum" in node:
        parts.append(f"value > {node['exclusiveMinimum']}")

    if node.get("additionalProperties") is False:
        parts.append("extra fields rejected")
    elif node.get("additionalProperties") is True:
        parts.append("extra fields allowed")

    return parts


def _constraints(node: Mapping[str, Any]) -> str:
    parts = _constraint_parts(node)
    return "; ".join(parts) if parts else "-"


def _required(schema: Mapping[str, Any], field: str) -> str:
    return "yes" if field in schema.get("required", []) else "no"


def _render_root_fields(schema: Mapping[str, Any]) -> list[str]:
    rows = []
    properties = schema.get("properties", {})
    if not isinstance(properties, Mapping):
        return _table(["Field", "Type", "Required", "Rules"], rows)

    required = [field for field in schema.get("required", []) if field in properties]
    optional = sorted(field for field in properties if field not in required)
    for field in [*required, *optional]:
        node = properties[field]
        if not isinstance(node, Mapping):
            continue
        rows.append([f"`{field}`", _type_summary(node), _required(schema, field), _constraints(node)])
    return _table(["Field", "Type", "Required", "Rules"], rows)


def _render_defs(schema_label: str, schema: Mapping[str, Any]) -> list[list[str]]:
    rows: list[list[str]] = []
    defs = schema.get("$defs", {})
    if not isinstance(defs, Mapping):
        return rows
    for name, node in defs.items():
        if not isinstance(node, Mapping):
            continue
        required = ", ".join(f"`{field}`" for field in node.get("required", [])) or "-"
        rows.append([schema_label, f"`{name}`", _type_summary(node), required, _constraints(node)])
    return rows


def render_wonder_schema_reference() -> str:
    """Render the committed Wonder schema reference."""
    loaded = [(label, path, _load_schema(path)) for label, path in SCHEMAS]

    source_rows = [
        [
            label,
            f"`{_repo_path(path)}`",
            schema.get("title", ""),
            schema.get("$id", ""),
        ]
        for label, path, schema in loaded
    ]

    identity_rows = [
        [
            label,
            schema.get("$schema", ""),
            schema.get("type", ""),
            f"`{_format_value(schema.get('additionalProperties'))}`",
            len(schema.get("required", [])),
        ]
        for label, _, schema in loaded
    ]

    sections = [
        "# Wonder Schema Reference",
        "",
        GENERATED_NOTICE,
        "",
        "This reference is generated from the committed Wonder JSON Schemas.",
        "",
        "## Source Schemas",
        "",
        *_table(["Contract", "Path", "Title", "Schema ID"], source_rows),
        "",
        "## Root Contract Summary",
        "",
        *_table(["Contract", "Draft", "Root type", "Root extra fields", "Required root fields"], identity_rows),
        "",
    ]

    definition_rows: list[list[str]] = []
    for label, _, schema in loaded:
        sections.extend(
            [
                f"## {label} Root Fields",
                "",
                *_render_root_fields(schema),
                "",
            ]
        )
        definition_rows.extend(_render_defs(label, schema))

    if definition_rows:
        sections.extend(
            [
                "## Reusable Definitions",
                "",
                *_table(["Contract", "Definition", "Type", "Required fields", "Rules"], definition_rows),
                "",
            ]
        )

    return "\n".join(sections)


def main() -> None:
    """Regenerate the committed Wonder schema reference file."""
    OUTPUT_PATH.write_text(render_wonder_schema_reference(), encoding="utf-8", newline="\n")
    print(f"wrote {_repo_path(OUTPUT_PATH)}")


if __name__ == "__main__":
    main()
