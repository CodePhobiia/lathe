"""Generate CLI reference docs from live ``python -m lathe.cli --help`` output."""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from lathe.cli import _build_parser

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = ROOT / "docs" / "cli_reference.md"
HELP_WIDTH = "100"
HELP_WORKERS = 4


def _iter_command_paths(
    parser: argparse.ArgumentParser,
    prefix: tuple[str, ...] = (),
) -> list[tuple[str, ...]]:
    paths = [prefix]
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, subparser in action.choices.items():
                paths.extend(_iter_command_paths(subparser, (*prefix, name)))
    return paths


def _help_for(path: tuple[str, ...]) -> str:
    command = [sys.executable, "-m", "lathe.cli", *path, "--help"]
    env = {
        **os.environ,
        "COLUMNS": HELP_WIDTH,
        "PYTHONIOENCODING": "utf-8",
    }
    result = subprocess.run(
        command,
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if result.returncode != 0:
        rendered = " ".join(["python", "-m", "lathe.cli", *path, "--help"])
        raise RuntimeError(f"{rendered} exited {result.returncode}:\n{result.stderr}")
    return result.stdout.replace("\r\n", "\n").rstrip()


def render_cli_reference() -> str:
    """Render the committed CLI reference from the current argparse help output."""
    parser = _build_parser()
    paths = _iter_command_paths(parser)
    with ThreadPoolExecutor(max_workers=HELP_WORKERS) as pool:
        help_blocks = dict(zip(paths, pool.map(_help_for, paths), strict=True))

    sections = [
        "# Lathe CLI Reference",
        "",
        "<!-- Generated by scripts/generate_cli_reference.py; do not edit by hand. -->",
        "",
        "This reference is generated from live `python -m lathe.cli ... --help` output.",
        "",
        "Regenerate it with:",
        "",
        "```bash",
        "python scripts/generate_cli_reference.py",
        "```",
    ]

    for path in paths:
        command_display = " ".join(("lathe", *path))
        help_command = " ".join(("python", "-m", "lathe.cli", *path, "--help"))
        sections.extend(
            [
                "",
                f"## `{command_display}`",
                "",
                "```text",
                f"$ {help_command}",
                help_blocks[path],
                "```",
            ]
        )

    return "\n".join(sections) + "\n"


def main() -> None:
    """Regenerate the committed CLI reference file."""
    OUTPUT_PATH.write_text(render_cli_reference(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
